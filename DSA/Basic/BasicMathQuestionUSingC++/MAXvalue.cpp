
#include <iostream>  // cout aur endl use karne ke liye
#include <algorithm> // max() function use karne ke liye

using namespace std;

int main() {

    // max() ek predefined function hai.
    // Ye do values mein se badi value return karta hai.
    cout << max(10, 20);

    // 10 aur 20 mein se 20 bada hai,
    // isliye output 20 aayega.

    return 0; // Program successfully end hua
}


// Output:

// ```text
// 20
// ```

// **Notes:**

// * `max(10, 20)` → `20` return karega.
// * `#include <algorithm>` → `max()` function ke liye.
// * `cout` → result ko screen par print karta hai.
// * `return 0;` → `main()` function successful completion indicate karta hai.

